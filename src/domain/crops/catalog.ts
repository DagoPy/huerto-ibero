import type { BookDuration, Crop, Propagation, Season } from './types'

/*
 * Fuente: "Cómo cultivar más vegetales", John Jeavons.
 * - Tabla de datos de cultivo de vegetales y hortalizas: columnas D (germinación),
 *   E (método), H y L (semanas en almácigo) y M (distancia en la cama).
 * - Tablas de referencia y planeación del huerto: columnas R (semanas a madurez),
 *   S (semanas de cosecha) y T (temporada de siembra).
 * Los códigos de letras (P, LG, Q, D, **, +...) se conservan en `bookValue`.
 */

const weeks = (bookValue: string, min: number, max: number = min): BookDuration => ({
  bookValue,
  range: { min, max, unit: 'weeks' },
})

const days = (bookValue: string, min: number, max: number = min): BookDuration => ({
  bookValue,
  range: { min, max, unit: 'days' },
})

const years = (bookValue: string, min: number, max: number = min): BookDuration => ({
  bookValue,
  range: { min, max, unit: 'years' },
})

/** Código "D": desconocido, el libro no da un número. */
const unknown = (bookValue = 'D'): BookDuration => ({ bookValue, range: null })

const inFlats = (...flats: BookDuration[]): Propagation => ({ method: 'flats', flats })

const direct = (notes?: string, maturity?: BookDuration): Propagation => ({
  method: 'direct',
  flats: [],
  notes,
  maturity,
})

const seasonCodes: Record<string, Season> = { PR: 'spring', VE: 'summer', OT: 'autumn', IN: 'winter' }

/** Convierte el texto de la columna T (p. ej. "PR, VE, OT"). */
const seasons = (codes: string): Season[] => codes.split(',').map((code) => seasonCodes[code.trim()])

